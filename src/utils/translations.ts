export type TranslationKey = keyof typeof TRANSLATIONS.ar;

export function getTranslation(lang: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.ar;
  let text = dict[key] || TRANSLATIONS.ar[key] || key;
  if (params) {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val)) as any;
    });
  }
  return text;
}
